#!/usr/bin/env python3
"""Writes docs/results/timedemo.md from the run statistics that
scripts/timedemo.sh leaves in build/results/ (one JSON + one frame-comparison
report per engine and demo)."""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "build", "results")
OUT = os.path.join(ROOT, "docs", "results", "timedemo.md")
DEMOS = [("demo1", "E1M5"), ("demo2", "E1M3"), ("demo3", "E1M7")]
ENGINES = ["iss", "fast", "accurate", "model"]


def load(tag):
    try:
        with open(os.path.join(RES, tag + ".json")) as f:
            stats = json.load(f)
        with open(os.path.join(RES, tag + ".cmp")) as f:
            cmp_text = f.read()
        with open(os.path.join(RES, tag + ".serial"), errors="replace") as f:
            serial = f.read()
    except OSError:
        return None
    m = re.search(r"compared (\d+) frames: (\d+) identical, (\d+) differing", cmp_text)
    stats["cmp_frames"], stats["cmp_same"], stats["cmp_diff"] = (int(x) for x in m.groups()) if m else (0, 0, -1)
    m = re.search(r"timed (\d+) gametics in (\d+) realtics \(([\d.]+) fps\)", serial)
    stats["doom_line"] = m.group(0) if m else "-"
    return stats


def n(x):
    return f"{int(x):,}".replace(",", " ")


def pct(x):
    return f"{100 * x:.2f} %"


def main():
    runs = {(e, d): load(f"{d}-{e}") for e in ENGINES for d, _ in DEMOS}
    cosim = load("demo3-accurate-cosim")
    cosim_model = load("demo3-accurate-cosim-model")
    missing = [f"{d}-{e}" for (e, d), s in runs.items() if s is None]
    if missing:
        sys.exit("missing results (run scripts/timedemo.sh): " + ", ".join(missing))

    L = []
    L.append("# Doom timedemo results\n")
    L.append("Generated by `tools/timedemo_report.py` from the files `scripts/timedemo.sh` writes to\n"
             "`build/results/`. Every run plays a recorded demo with `-timedemo`, dumps every frame the\n"
             "program presents, and compares the dump pixel for pixel (after palette lookup) with the\n"
             "dump of native doomgeneric built from the same patched sources.\n")
    L.append("Reproduce one row: `make timedemo ENGINE=accurate DEMO=demo3`. Clock: 50 MHz.\n")

    L.append("## Frames identical to native doomgeneric\n")
    L.append("| Demo | Map | Frames | golden model (`iss`) | RTL, `fast` | RTL, `accurate` | cycle-exact `model` |")
    L.append("|---|---|---|---|---|---|---|")
    total = 0
    for d, m in DEMOS:
        row = [d, m, n(runs[("accurate", d)]["cmp_frames"])]
        for e in ENGINES:
            s = runs[(e, d)]
            row.append(f"{n(s['cmp_same'])} identical, {n(s['cmp_diff'])} differing")
        total += runs[("accurate", d)]["cmp_frames"]
        L.append("| " + " | ".join(row) + " |")
    L.append(f"\n{n(total)} frames per engine.\n")

    for e, title in (("accurate", "Accurate engine: SDRAM pin timing, real video scan-out"),
                     ("fast", "Fast engine: same CPU and caches, ideal memory"),
                     ("model", "Cycle-exact model: the accurate machine's timing in software, no RTL")):
        L.append(f"## {title}\n")
        L.append("| | " + " | ".join(d for d, _ in DEMOS) + " |")
        L.append("|---|" + "---|" * len(DEMOS))
        rows = [
            ("Cycles", lambda s: n(s["cycles"])),
            ("Instructions retired", lambda s: n(s["instret"])),
            ("Instructions per cycle", lambda s: f"{s['ipc']:.3f}"),
            ("I-cache miss rate", lambda s: pct(1 - s["ic_hit_rate"])),
            ("D-cache miss rate", lambda s: pct(1 - s["dc_hit_rate"])),
            ("Conditional branches mispredicted", lambda s: pct(1 - s["branch_accuracy"])),
            ("Jumps mispredicted", lambda s: pct(1 - s["jump_accuracy"])),
            ("Frames presented", lambda s: n(s["frames"])),
            ("Cycles per frame (first to last frame)",
             lambda s: n(round((s["last_frame_cycle"] - s["first_frame_cycle"]) / (s["frames"] - 1)))),
            ("**Frames per second at 50 MHz** (first to last frame)", lambda s: f"**{s['fps_span']:.2f}**"),
            ("Doom's own report", lambda s: s["doom_line"]),
        ]
        if e == "accurate":
            rows += [
                ("SDRAM row activations", lambda s: n(s["sdram activates"])),
                ("SDRAM protocol/timing violations", lambda s: n(s["sdram_violations"])),
                ("Serial / video timing errors", lambda s: f"{s['serial_errors']} / {s['video_errors']}"),
                ("Scan-out frames checked against the framebuffer", lambda s: n(s["scan_checked"])),
                ("... of which different", lambda s: n(s["scan_bad"])),
                ("Scan-out frames not checkable (framebuffer changed meanwhile)", lambda s: n(s["scan_skipped"])),
            ]
        rows.append(("Simulation speed (million cycles per wall-clock second)", lambda s: f"{s['speed']:.1f}"))
        for label, fn in rows:
            L.append(f"| {label} | " + " | ".join(fn(runs[(e, d)]) for d, _ in DEMOS) + " |")
        L.append("")

    L.append("\"First to last frame\" excludes program start-up before the first frame. Doom's own report\n"
             "divides game tics by its cycle-counter clock over the whole demo, including level loading.\n"
             "Simulation speed depends on what else the machine was doing during the run.\n")

    if cosim_model:
        L.append("## Lockstep run against the cycle-exact model\n")
        L.append("demo3 on the accurate engine with the `model` engine running alongside; for every retired\n"
                 "instruction the retire record, the cycle it retires in and all eleven counters are compared,\n"
                 "with no overrides for MMIO or counter reads; frames and serial bytes with their cycles too:\n")
        L.append(f"- instructions compared: {n(cosim_model['cosim_instructions'])}, deviations: 0 (a deviation ends the run)")
        L.append(f"- frames identical to native: {n(cosim_model['cmp_same'])} of {n(cosim_model['cmp_frames'])}\n")

    if cosim:
        L.append("## Lockstep run against the golden model\n")
        L.append("demo3 on the accurate engine with the golden model executing every retired instruction\n"
                 "alongside the RTL and comparing program counter, instruction, register write, memory\n"
                 "access and next PC:\n")
        L.append(f"- instructions compared: {n(cosim['cosim_instructions'])}, mismatches: 0 (a mismatch ends the run)")
        L.append(f"- frames compared between the two models at each flip: {n(cosim['cosim frames compared'])}")
        L.append(f"- frames identical to native: {n(cosim['cmp_same'])} of {n(cosim['cmp_frames'])}")
        L.append(f"- SDRAM violations: {cosim['sdram_violations']}; scan-out frames checked: "
                 f"{n(cosim['scan_checked'])}, different: {cosim['scan_bad']}\n")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
